// Pulls every feed in the OPML server-side (no browser CORS limits) and
// writes app/js/news-data.js: the snapshot the Reading page shows before,
// or instead of, a live refresh. Run: npm run news
// A feed that fails keeps its items from the previous snapshot.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { newsParse, newsTopics } = require('../app/js/news-core.js');

const feedsSrc = readFileSync('app/js/feeds-data.js', 'utf8');
const FEEDS = JSON.parse(feedsSrc.slice(feedsSrc.indexOf('{'), feedsSrc.lastIndexOf('}') + 1));
const feeds = FEEDS.groups.flatMap(g => g.items);
const OUT = 'app/js/news-data.js';
let prev = { items: [] };
if (existsSync(OUT)) { const t = readFileSync(OUT, 'utf8'); try { prev = JSON.parse(t.slice(t.indexOf('{'), t.lastIndexOf('}') + 1)); } catch (e) { /* start fresh */ } }

const PER_FEED = 8, TIMEOUT = 20000;
const pull = async f => {
  const ctl = new AbortController(); const tm = setTimeout(() => ctl.abort(), TIMEOUT);
  try {
    const r = await fetch(f.xml, { signal: ctl.signal, redirect: 'follow', headers: { 'user-agent': 'Mozilla/5.0 (compatible; feed-reader)', accept: 'application/rss+xml, application/atom+xml, application/xml, text/xml;q=0.9, */*;q=0.5' } });
    if (!r.ok) throw new Error('HTTP ' + r.status);
    const items = newsParse(await r.text(), f.title, PER_FEED);
    if (!items.length) throw new Error('no items');
    return { f, items };
  } catch (e) { return { f, err: e.message || String(e) }; } finally { clearTimeout(tm); }
};

const results = await Promise.all(feeds.map(async f => { const r = await pull(f); return r.items ? r : pull(f); }));  // one retry
const items = [], failed = [];
for (const { f, items: got, err } of results) {
  if (got) items.push(...got);
  else { failed.push(f.title + ' (' + err + ')'); items.push(...prev.items.filter(x => x.src === f.title)); }
}
items.forEach(it => { it.topics = newsTopics(it); });
items.sort((a, b) => b.date - a.date);
const data = { at: Date.now(), ok: results.length - failed.length, total: results.length, items };
// JSON inside a script: escape < and the JS line separators.
const json = JSON.stringify(data).replace(/</g, '\\u003c').replace(new RegExp(String.fromCharCode(0x2028), 'g'), '\\u2028').replace(new RegExp(String.fromCharCode(0x2029), 'g'), '\\u2029');
writeFileSync(OUT, "'use strict';\n/* Generated by scripts/pull-news.mjs. Do not edit by hand. */\nconst NEWS = " + json + ';\n');
console.log('news: ' + items.length + ' items from ' + data.ok + '/' + data.total + ' feeds' + (failed.length ? '; failed: ' + failed.join(', ') : ''));
