// Reads app/ai-security-governance-mlops.opml and writes app/js/feeds-data.js,
// so the Reading page works from file:// and on any static host (no fetch).
// Run after editing the OPML: npm run feeds
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'app/ai-security-governance-mlops.opml';
const xml = readFileSync(SRC, 'utf8');
const dec = s => s.replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const attrs = tag => Object.fromEntries([...tag.matchAll(/(\w+)="([^"]*)"/g)].map(m => [m[1], dec(m[2])]));

const title = dec((xml.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || 'Reading list');
const body = (xml.match(/<body>([\s\S]*)<\/body>/) || [])[1] || '';
const groups = [];
// A group is an <outline> without type="rss" that wraps rss outlines.
for (const m of body.matchAll(/<outline((?:(?!type="rss")[^>])*)>([\s\S]*?)<\/outline>/g)) {
  const g = attrs(m[1]);
  const items = [...m[2].matchAll(/<outline([^>]*type="rss"[^>]*)\/>/g)].map(x => {
    const a = attrs(x[1]);
    const [, note = ''] = a.text.split(/\s+—\s+/);
    return { title: a.title || a.text, note: note.trim(), xml: a.xmlUrl, html: a.htmlUrl };
  });
  if (items.length) groups.push({ name: g.title || g.text, items });
}
if (!groups.length) throw new Error('no feed groups found in ' + SRC);

const out = "'use strict';\n/* Generated by scripts/import-opml.mjs from " + SRC.replace('app/', '') + ". Do not edit by hand. */\n"
  + 'const FEEDS = ' + JSON.stringify({ title, file: SRC.replace('app/', ''), groups }, null, 1) + ';\n';
writeFileSync('app/js/feeds-data.js', out);
console.log('feeds: ' + groups.map(g => g.name + ' ' + g.items.length).join(', '));

// The optional live-news proxy: a Cloudflare Worker that fetches only the
// feeds in this OPML (an allowlist, so it is not an open proxy), caches each
// for 15 minutes and adds the CORS header browsers need. Deploy it, then set
// NEWS_PROXY in app/js/feeds.js to 'https://<your-worker>/?url='.
const allow = groups.flatMap(g => g.items.map(i => i.xml));
writeFileSync('scripts/feed-proxy-worker.js', `// Generated by scripts/import-opml.mjs from ${SRC}. Deploy with: npx wrangler deploy scripts/feed-proxy-worker.js --name ai-feeds
const ALLOW = new Set(${JSON.stringify(allow, null, 1)});
export default {
  async fetch(req) {
    const cors = { 'access-control-allow-origin': '*', 'access-control-allow-methods': 'GET', 'vary': 'origin' };
    if (req.method === 'OPTIONS') return new Response(null, { headers: cors });
    const url = new URL(req.url).searchParams.get('url');
    if (req.method !== 'GET' || !url || !ALLOW.has(url)) return new Response('not an allowed feed', { status: 403, headers: cors });
    const r = await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0 (compatible; feed-reader)' }, cf: { cacheTtl: 900, cacheEverything: true } });
    return new Response(r.body, { status: r.status, headers: { ...cors, 'content-type': r.headers.get('content-type') || 'application/xml', 'cache-control': 'public, max-age=900' } });
  }
};
`);
console.log('proxy allowlist: ' + allow.length + ' feeds → scripts/feed-proxy-worker.js');
